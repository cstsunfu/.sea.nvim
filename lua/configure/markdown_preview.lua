local plugin = {}

local width_order = { "narrow", "standard", "wide", "full" }
local widths = {
    narrow = { label = "窄（720px）", value = "720px" },
    standard = { label = "标准（900px）", value = "900px" },
    wide = { label = "宽（1200px）", value = "1200px" },
    full = { label = "全宽", value = "none" },
}

local function write_runtime_css(width_name)
    local source = vim.g.CONFIG .. "/lua/util/markdown.css"
    local cache_dir = vim.fn.stdpath("cache") .. "/markdown-preview"
    local target = cache_dir .. "/markdown.css"
    local width = widths[width_name] or widths.standard
    local page_width = width.value == "none" and "calc(100vw - 32px)" or width.value
    local lines = vim.fn.readfile(source)

    vim.list_extend(lines, {
        "",
        "/* Generated by lua/configure/markdown_preview.lua. */",
        "#page-ctn {",
        "    box-sizing: border-box;",
        "    --preview-page-width: " .. page_width .. ";",
        "    width: 100%;",
        "    max-width: " .. width.value .. ";",
        "}",
    })

    vim.fn.mkdir(cache_dir, "p")
    if vim.fn.writefile(lines, target) ~= 0 then
        error("Failed to write Markdown Preview CSS: " .. target)
    end

    vim.g.mkdp_markdown_css = target
    vim.g.markdown_preview_width = width_name
end

local function set_preview_width(width_name)
    if not widths[width_name] then
        vim.notify("Unknown Markdown Preview width: " .. width_name, vim.log.levels.ERROR)
        return
    end

    local was_open = vim.g.mkdp_clients_active == 1 or vim.b.MarkdownPreviewToggleBool == 1
    write_runtime_css(width_name)
    vim.notify("Markdown Preview width: " .. widths[width_name].label)

    -- A running preview must reload its stylesheet to see the generated CSS.
    if was_open then
        vim.fn["mkdp#util#stop_preview"]()
        vim.defer_fn(function()
            vim.fn["mkdp#util#toggle_preview"]()
        end, 150)
    end
end

local function select_preview_width()
    local items = {}
    for _, name in ipairs(width_order) do
        table.insert(items, { name = name, label = widths[name].label })
    end

    vim.ui.select(items, {
        prompt = "Markdown Preview 页面宽度",
        format_item = function(item)
            local selected = item.name == vim.g.markdown_preview_width and " ✓" or ""
            return item.label .. selected
        end,
    }, function(item)
        if item then
            set_preview_width(item.name)
        end
    end)
end

plugin.core = {
    "iamcco/markdown-preview.nvim",
    --    build = "cd app && npm install",
    build = function()
        vim.fn["mkdp#util#install"]()
    end,
    ft = { "markdown", "vimwiki", "vimwiki.markdown.pandoc" },
    --cmd = "MarkdownPreviewToggle",

    init = function() -- Specifies code to run before this plugin is loaded.
        vim.g.mkdp_filetypes = { "markdown", "vimwiki", "vimwiki.markdown.pandoc" }
        vim.g.mkdp_theme = "dark"
    end,

    config = function() -- Specifies code to run after this plugin is loaded
        local default_width = widths[vim.g.markdown_preview_width] and vim.g.markdown_preview_width or "wide"
        write_runtime_css(default_width)

        pcall(vim.api.nvim_del_user_command, "MarkdownPreviewSmart")
        vim.api.nvim_create_user_command("MarkdownPreviewSmart", function()
            require("util.obsidian_preview").toggle()
        end, {
            desc = "Preview Markdown with automatic Obsidian detection and local link navigation",
        })

        -- Backward-compatible alias for the previous command name.
        pcall(vim.api.nvim_del_user_command, "MarkdownPreviewObsidian")
        vim.api.nvim_create_user_command("MarkdownPreviewObsidian", function()
            require("util.obsidian_preview").toggle()
        end, {
            desc = "Alias for MarkdownPreviewSmart",
        })

        pcall(vim.api.nvim_del_user_command, "MarkdownPreviewWidth")
        vim.api.nvim_create_user_command("MarkdownPreviewWidth", function(args)
            if args.args == "" then
                select_preview_width()
            else
                set_preview_width(args.args)
            end
        end, {
            nargs = "?",
            complete = function(arg_lead)
                return vim.tbl_filter(function(name)
                    return vim.startswith(name, arg_lead)
                end, width_order)
            end,
            desc = "Select Markdown Preview page width",
        })
    end,
}

plugin.mapping = function()
    local mappings = require("core.mapping")
    mappings.register({
        mode = "n",
        key = { "<leader>", "m", "p" },
        action = ":MarkdownPreviewSmart<cr>",
        short_desc = "Markdown Preview Smart",
        silent = true,
    })
    mappings.register({
        mode = "n",
        key = { "<leader>", "m", "w" },
        action = ":MarkdownPreviewWidth<cr>",
        short_desc = "Markdown Preview Width",
        silent = true,
    })
end
return plugin
